print("@__________For Loop__________@")

print("_____'for' loop for list_____")

items = ["apple", 34, "banana", "mango"]
for item in items:
    print(item)


print("_____'for' loop for range_____")

for i in range(0, 10, 2):
    print(i)


print("_____'for' loop for characters_____")

for char in "Amandeep":
    print(char)




print("@__________While Loop__________@")

count = 1
while(count<=5):
    print(count)
    count += 1

print("End of program")